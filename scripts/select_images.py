# One-time offline script: choose up to 3 images per notes section from the AI-classified candidates and wire them into the app.
# Writes: frontend/assets/slides/x_*.jpg, frontend/src/data/extraSlides.ts, frontend/src/data/extraMedia.json
import json, os, shutil
from PIL import Image

C = '/tmp/cand'
FE = '/app/frontend'
ASSETS = f'{FE}/assets/slides'
cands = {c['cid']: c for c in json.load(open(f'{C}/candidates.json'))}
cls = json.load(open(f'{C}/classified.json'))
sections = json.load(open(f'{C}/sections.json'))


def dhash(path, n=8):
    im = Image.open(path).convert('L').resize((n + 1, n))
    px = list(im.getdata())
    return sum(1 << i for i in range(n * n) if px[(i // n) * (n + 1) + i % n] > px[(i // n) * (n + 1) + i % n + 1])


existing = [dhash(f'{ASSETS}/{f}') for f in os.listdir(ASSETS) if f.endswith('.jpg') and not f.startswith('x_')]
used = list(existing)


def is_dup(h):
    return any(bin(h ^ u).count('1') <= 6 for u in used)


extra, keys = {}, []
for topic, secs in sections.items():
    pool = [(cid, r) for cid, r in cls.items() if cands[cid]['topic'] == topic and r.get('section') and r.get('type') in ('sonogram', 'anatomy', 'diagram') and (r.get('quality') or 0) >= 3]
    pool.sort(key=lambda x: (-(x[1].get('quality') or 0), cands[x[0]]['src'] != 's'))
    m = extra.setdefault(topic, {'sectionImages': [], 'imageCards': []})
    for s in secs:
        slots = 3 - s['n']
        if slots <= 0:
            continue
        mine = [p for p in pool if p[1]['section'] == s['title']]
        # Prefer variety: best ultrasound first, then best anatomy/diagram, then the next best of any type.
        order = [p for p in mine if p[1]['type'] == 'sonogram'][:1] + [p for p in mine if p[1]['type'] != 'sonogram'][:1]
        order += [p for p in mine if p not in order]
        picked = 0
        for cid, r in order:
            if picked >= slots:
                break
            src = f"{C}/{topic}/{cid}.jpg"
            h = dhash(src)
            if is_dup(h):
                continue
            used.append(h)
            key = f"x_{topic}_{len(keys) + 1}"
            im = Image.open(src)
            im.thumbnail((720, 720))
            im.save(f'{ASSETS}/{key}.jpg', quality=70)
            keys.append(key)
            quizzable = r['type'] == 'sonogram' and not r.get('answer_in_image') and r['quality'] >= 4
            m['sectionImages'].append({'section': s['title'], 'key': key, 'caption': r['caption'], 'kind': r['type'], **({} if quizzable else {'quiz': False})})
            if quizzable:
                m['imageCards'].append({'key': key, 'back': r['caption']})
            picked += 1

json.dump(extra, open(f'{FE}/src/data/extraMedia.json', 'w'), indent=1)
with open(f'{FE}/src/data/extraSlides.ts', 'w') as f:
    f.write('// Images matched to notes sections from the course slides and the 3rd edition textbook (generated by scripts/select_images.py).\n')
    f.write('export const extraSlides = {\n')
    for k in keys:
        f.write(f'  {k}: require("../../assets/slides/{k}.jpg"),\n')
    f.write('};\n')
print('added', len(keys), 'cards', sum(len(v['imageCards']) for v in extra.values()))
