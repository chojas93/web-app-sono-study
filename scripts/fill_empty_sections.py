# Second pass for sections still without pictures: AI picks up to 2 fitting candidates by caption (reuse allowed).
import asyncio, json, os, re
from dotenv import load_dotenv
from PIL import Image
from emergentintegrations.llm.chat import LlmChat, UserMessage, TextDelta, StreamDone

load_dotenv('/app/backend/.env')
C, FE = '/tmp/cand', '/app/frontend'
cands = {c['cid']: c for c in json.load(open(f'{C}/candidates.json'))}
cls = json.load(open(f'{C}/classified.json'))
secs = json.load(open(f'{C}/sections.json'))
ex = json.load(open(f'{FE}/src/data/extraMedia.json'))
keys = re.findall(r'^  (x_\w+):', open(f'{FE}/src/data/extraSlides.ts').read(), re.M)
picked_by_cid = json.load(open(f'{C}/picked.json')) if os.path.exists(f'{C}/picked.json') else {}

SYS = ("You match study-guide sections to images by caption. Return ONLY JSON {\"ids\": [..]} with up to 2 image ids whose caption clearly shows "
       "the subject of the section (same disease, structure, technique or concept). Return {\"ids\": []} if none clearly fit — do not guess.")


async def pick(topic, sec, opts):
    chat = LlmChat(api_key=os.environ['EMERGENT_LLM_KEY'], session_id=f'p2-{topic}-{sec}', system_message=SYS).with_model('openai', 'gpt-5.4')
    prompt = f"SECTION: {sec}\nIMAGES:\n" + '\n'.join(f"{i}: [{r['type']}] {r['caption']}" for i, (cid, r) in enumerate(opts))
    txt = ''
    async for ev in chat.stream_message(UserMessage(text=prompt)):
        if isinstance(ev, TextDelta):
            txt += ev.content
        elif isinstance(ev, StreamDone):
            break
    ids = json.loads(re.search(r'\{.*\}', txt, re.S).group(0)).get('ids', [])
    return [opts[int(i)] for i in ids if str(i).isdigit() and int(i) < len(opts)][:2]


async def main():
    jobs = []
    for t, ss in secs.items():
        opts = [(cid, r) for cid, r in cls.items() if cands[cid]['topic'] == t and r.get('type') in ('sonogram', 'anatomy', 'diagram') and (r.get('quality') or 0) >= 3]
        for s in ss:
            if s['n'] + sum(1 for x in ex[t]['sectionImages'] if x['section'] == s['title']) == 0:
                jobs.append((t, s['title'], opts))
    res = await asyncio.gather(*(pick(t, s, o) for t, s, o in jobs))
    added = 0
    for (t, s, _), chosen in zip(jobs, res):
        for cid, r in chosen:
            key = picked_by_cid.get(cid)
            if not key:
                key = f'x_{t}_{len(keys) + 1}'
                im = Image.open(f'{C}/{t}/{cid}.jpg')
                im.thumbnail((720, 720))
                im.save(f'{FE}/assets/slides/{key}.jpg', quality=70)
                keys.append(key)
                picked_by_cid[cid] = key
            ex[t]['sectionImages'].append({'section': s, 'key': key, 'caption': r['caption'], 'kind': r['type'], 'quiz': False})
            added += 1
        print(t, '|', s, '->', [r['caption'] for _, r in chosen])
    json.dump(ex, open(f'{FE}/src/data/extraMedia.json', 'w'), indent=1)
    with open(f'{FE}/src/data/extraSlides.ts', 'w') as f:
        f.write('// Images matched to notes sections from the course slides and the 3rd edition textbook (generated by scripts/select_images.py).\n')
        f.write('export const extraSlides = {\n' + ''.join(f'  {k}: require("../../assets/slides/{k}.jpg"),\n' for k in keys) + '};\n')
    print('added', added)

asyncio.run(main())
